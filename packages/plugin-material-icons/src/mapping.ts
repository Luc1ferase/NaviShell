/**
 * The icon name for an entry, or `undefined` for the kinds this theme leaves to the host
 * (symlinks and special files keep the host's own glyphs).
 */
export function iconNameFor(request: FileIconRequest): string | undefined {
  if (request.kind === 'dir') return FOLDER_NAMES[request.name.toLowerCase()] ?? 'folder';
  if (request.kind !== 'file') return undefined;
  const name = request.name.toLowerCase();
  const exact = FILE_NAMES[name];
  if (exact !== undefined) return exact;
  for (const [prefix, icon] of FILE_NAME_PREFIXES) {
    if (name.startsWith(prefix)) return icon;
  }
  return EXTENSIONS[request.extension] ?? 'document';
}
