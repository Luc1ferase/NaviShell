let flattened: DictionaryEntry[] | null = null;

function toEntry(command: string, base: string, row: Row, sub: boolean): DictionaryEntry {
  return {
    command,
    base,
    description: { en: row[1], 'zh-CN': row[2] },
    sub,
  };
}

/** Flattened dictionary (`git` and `git commit` are separate entries). Cached. */
export function dictionary(): readonly DictionaryEntry[] {
  if (flattened) return flattened;
  const entries: DictionaryEntry[] = COMMANDS.map((row) => toEntry(row[0], row[0], row, false));
  for (const [base, rows] of Object.entries(SUBCOMMANDS)) {
    for (const row of rows) {
      entries.push(toEntry(`${base} ${row[0]}`, base, row, true));
    }
  }
  flattened = entries;
  return flattened;
}

